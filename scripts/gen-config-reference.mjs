#!/usr/bin/env node
// docs/CONFIGURATION.md called its hand-written example a "Full reference"
// while covering 59 of 165 keys. Seven of the missing ones default to off,
// including `safety.allow_git_push` and `safety.allow_network_commands`, and
// beta.136 had already been spent documenting two others after a real run cost
// $22.67 discovering one of them was unset.
//
// A hand-maintained list of 165 keys drifts the week it is written, so the
// appendix is generated from openclaw.plugin.json — the same schema the gateway
// validates against, which makes it authoritative about what an operator may
// actually set. `npm run docs:config` rewrites it; a test fails the build when
// the committed block no longer matches.
//
// Usage:
//   node scripts/gen-config-reference.mjs           rewrite the block
//   node scripts/gen-config-reference.mjs --check   exit 1 if it is stale
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const DOC = join(root, "docs", "CONFIGURATION.md");
export const START = "<!-- BEGIN GENERATED CONFIG REFERENCE -->";
export const END = "<!-- END GENERATED CONFIG REFERENCE -->";

const tidy = (s) => String(s ?? "").replace(/\s+/g, " ").trim();

function describeType(node) {
  if (node.enum) return node.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (Array.isArray(node.type)) return node.type.join(" | ");
  if (node.type === "array") return node.items?.type ? `${node.items.type}[]` : "array";
  return node.type ?? "object";
}

// A JSON Schema `default` is an annotation: it describes a value, it does not
// supply one, and b99 shipped a key whose declared default was never in
// DEFAULTS. So the effective default is read from the parsed config — what the
// harness will actually run with — and the schema annotation is only a
// fallback for keys the parser leaves unset.
function describeDefault(node, effective) {
  const d = effective !== undefined ? effective : node.default;
  if (d === undefined) return "no default; unset unless you set it";
  if (Array.isArray(d)) return d.length ? `default \`${JSON.stringify(d)}\`` : "default `[]` (empty)";
  if (d === "") return 'default `""` (empty)';
  if (d && typeof d === "object") {
    return Object.keys(d).length ? `default \`${JSON.stringify(d)}\`` : "default `{}` (empty)";
  }
  return `default \`${JSON.stringify(d)}\``;
}

/** The value the harness actually resolves for a dotted path, or undefined. */
function effectiveValue(resolved, dotted) {
  let node = resolved;
  for (const seg of dotted.split(".")) {
    if (node === null || typeof node !== "object" || !(seg in node)) return undefined;
    node = node[seg];
  }
  return typeof node === "object" && node !== null && !Array.isArray(node) ? undefined : node;
}

/** Leaf entries in declaration order, grouped by top-level section. */
function collect(node, resolved, path = []) {
  if (!node || typeof node !== "object") return [];
  if (!node.properties) {
    if (!path.length) return [];
    const key = path.join(".");
    return [
      {
        key,
        type: describeType(node),
        def: describeDefault(node, effectiveValue(resolved, key)),
        desc: tidy(node.description),
      },
    ];
  }
  return Object.entries(node.properties).flatMap(([k, v]) => collect(v, resolved, [...path, k]));
}

export function renderReference(manifest, resolved = {}) {
  const schema = manifest.configSchema;
  const lines = [
    START,
    "",
    "<!-- Generated by scripts/gen-config-reference.mjs from openclaw.plugin.json.",
    "     Do not edit by hand; run `npm run docs:config`. -->",
    "",
    "Every key the gateway will accept, in declaration order. A key absent from",
    "this list is rejected: the manifest is `additionalProperties: false`, so an",
    "unrecognised key fails the whole plugin config, not just that line.",
    "",
    "Defaults are the values the harness resolves when you set nothing, read from",
    "the parser rather than from a schema annotation. Where a value is an array,",
    "setting it REPLACES the default rather than extending it.",
    "",
  ];

  for (const [section, node] of Object.entries(schema.properties)) {
    const entries = collect(node, resolved, [section]);
    if (!entries.length) continue;
    lines.push(`#### \`${section}\``, "");
    const blurb = tidy(node.description);
    if (blurb) lines.push(blurb, "");
    for (const e of entries) {
      lines.push(`- **\`${e.key}\`** — \`${e.type}\`, ${e.def}.${e.desc ? " " + e.desc : ""}`);
    }
    lines.push("");
  }

  lines.push(END);
  return lines.join("\n");
}

function currentBlock(doc) {
  const a = doc.indexOf(START);
  const b = doc.indexOf(END);
  if (a === -1 || b === -1) return null;
  return doc.slice(a, b + END.length);
}

/**
 * The config the harness resolves from the smallest input it will accept, so
 * every value below it is a genuine default rather than something we asserted.
 */
export async function resolvedDefaults() {
  const { parseHarnessConfig } = await import(new URL("../dist/config.js", import.meta.url).href);
  return parseHarnessConfig({
    slack: { channel: "C0XXXXXXXXX", authorised_users: ["U000000"] },
    repos: { allowed: ["example-org/example-repo"] },
  });
}

async function main() {
  const manifest = JSON.parse(readFileSync(join(root, "openclaw.plugin.json"), "utf8"));
  const rendered = renderReference(manifest, await resolvedDefaults());
  const doc = readFileSync(DOC, "utf8");
  const existing = currentBlock(doc);
  if (existing === null) {
    console.error(`No ${START} / ${END} markers in docs/CONFIGURATION.md.`);
    process.exit(2);
  }
  if (process.argv.includes("--check")) {
    if (existing === rendered) {
      console.log("config reference is current");
      return;
    }
    console.error("docs/CONFIGURATION.md config reference is stale. Run `npm run docs:config`.");
    process.exit(1);
  }
  writeFileSync(DOC, doc.replace(existing, rendered), "utf8");
  const count = (rendered.match(/^- \*\*`/gm) ?? []).length;
  console.log(`wrote ${count} keys into docs/CONFIGURATION.md`);
}

if (process.argv[1] && process.argv[1].endsWith("gen-config-reference.mjs")) main();
